-- 2 Tabelas
-- 1 – Selecione o nome dos autores que já escreveram livros
SELECT DISTINCT(a.nome), a.codautor FROM autor a
	INNER JOIN livro_autor la
	ON a.codautor = la.codautor
	ORDER BY a.nome;


-- 2 – Selecione o nome dos alunos e seus telefones.
SELECT a.nome, telefone FROM aluno a
	INNER JOIN telefone_aluno tel
	ON a.prontuario = tel.prontuario
	ORDER BY a.nome;

	
-- 3 – Selecione o nome dos livros e a quantidade de atores de 
-- cada livro, desde que a quantidade seja maior que 2.
SELECT liv.titulo, COUNT(codAutor) AS "Qtd. Autores" FROM livro liv
	INNER JOIN livro_autor la
	ON la.codlivro = liv.codlivro
	GROUP BY liv.titulo
	HAVING COUNT(codAutor) > 2
	ORDER BY liv.titulo;


-- 4 – Selecione o nome de todos os alunos e a quantidade de 
-- livros que já fizeram empréstimo em 2026.
SELECT alu.nome, COUNT(*) AS "Qtd. Empréstimo",
	FROM aluno alu 
	INNER JOIN emprestimo emp ON alu.prontuario = emp.prontuario 
	WHERE emp.dtaempr BETWEEN '2026-01-01' AND '2026-12-31' 
	GROUP BY alu.nome 
	ORDER BY alu.nome;


-- 5 – Selecione o nome dos autores e dos livros que escreveram.
SELECT aut.nome, liv.titulo FROM autor aut
	INNER JOIN livro_autor la
	ON aut.codautor = la.codautor
	INNER JOIN livro liv
	ON la.codlivro = liv.codlivro
	ORDER BY aut.nome;
	-- ORDER BY liv.titulo;


-- 6 – Selecione o nome dos autores e dos livros que 
-- escreveram dos livros de Romance.
SELECT aut.nome, liv.titulo, genero FROM autor aut
	INNER JOIN livro_autor la
	ON aut.codautor = la.codautor
	INNER JOIN livro liv
	ON la.codlivro = liv.codlivro
	WHERE genero = 'Romance'
	ORDER BY aut.nome;


-- 7 – Selecione o nome dos alunos que fizeram algum empréstimo de 
-- livro, os títulos dos livros e os telefones dos alunos. 
-- Dica: não usar a tabela exemplar – realizar junção direta do codLivro de 
-- empréstimo com Livro.
SELECT alu.nome, liv.titulo, tel.telefone FROM aluno alu
	INNER JOIN emprestimo emp
	ON alu.prontuario = emp.prontuario
	INNER JOIN livro liv
	ON emp.codlivro = liv.codlivro
	INNER JOIN telefone_aluno tel
	ON alu.prontuario = tel.prontuario;
	

-- 8 – Selecione o nome dos autores e dos livros que escreveram
-- desde que tenham sido realizados empréstimos em 2025. Ordene pela data.
SELECT aut.nome, liv.titulo, emp.dtaempr FROM autor aut
	INNER JOIN livro_autor la
	ON aut.codautor = la.codautor
	INNER JOIN livro liv
	ON la.codlivro = liv.codlivro
	INNER JOIN emprestimo emp
	ON liv.codlivro = emp.codlivro
	WHERE emp.dtaempr BETWEEN '2025-01-01' AND '2025-12-31' 
	ORDER BY emp.dtaempr;
	
	-- Pelo exemplar: 
	-- (exemplar.numExemplar, ex.codLivro) = (emprestimo.numExemplar, emprestimo.codLivro)

-- 9 – Selecione o nome dos alunos que fizeram algum empréstimo de livros 
