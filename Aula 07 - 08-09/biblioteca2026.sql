	ON alu.prontuario = emp.prontuario
	INNER JOIN livro liv
	ON emp.codlivro = liv.codlivro
	INNER JOIN livro_autor la
	ON la.codlivro = liv.codlivro
	INNER JOIN autor aut
	ON aut.codautor = la.codautor
	
	WHERE aut.nome = 'Machado de Assis';


